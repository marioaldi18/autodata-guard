"""Markdown report built only from computed results."""
from __future__ import annotations

from typing import Any, Dict

import pandas as pd


def md_table(df: pd.DataFrame, float_fmt: str = "{:.3f}") -> str:
    cols = list(df.columns)
    lines = ["| " + " | ".join(map(str, cols)) + " |", "|" + "|".join("---" for _ in cols) + "|"]
    for row in df.itertuples(index=False):
        cells = []
        for v in row:
            if v is None or (isinstance(v, float) and pd.isna(v)):
                cells.append("n/a")
            elif isinstance(v, float):
                cells.append(float_fmt.format(v))
            else:
                cells.append(str(v))
        lines.append("| " + " | ".join(cells) + " |")
    return "\n".join(lines)


def build_insights(r: Dict[str, Any]) -> list:
    out = []
    ev = r["validation"]["rule_engine_eval"]
    out.append(f"The rule engine flagged {ev['n_flagged_rows']} rows; {ev['true_positive_rows']} of "
               f"{ev['n_injected_rows']} injected data-quality rows were caught "
               f"(recall {ev['recall']:.3f}, precision {ev['precision']:.3f}).")
    sel = r["selected_model"]
    m = r["models"][sel]
    base = r["models"]["robust_zscore_baseline"]
    lift = m["test"]["pr_auc"] / m["test"]["prevalence"] if m["test"]["prevalence"] else float("nan")
    out.append(f"The selected detector ({sel}, chosen by validation PR-AUC) reached test PR-AUC "
               f"{m['test']['pr_auc']:.3f} versus a prevalence baseline of {m['test']['prevalence']:.3f} "
               f"({lift:.1f}x lift) and test ROC-AUC {m['test']['roc_auc']:.3f}.")
    delta = m["test"]["pr_auc"] - base["test"]["pr_auc"]
    if sel == "robust_zscore_baseline":
        out.append("The simple robust z-score baseline was the best model on validation PR-AUC, "
                   "so the more complex detectors did not add value on this dataset.")
    elif delta > 0:
        out.append(f"It improved test PR-AUC by {delta:.3f} over the robust z-score baseline "
                   f"({base['test']['pr_auc']:.3f}).")
    else:
        out.append(f"It did not beat the robust z-score baseline on test PR-AUC (difference {delta:+.3f}).")
    t = m["test"]["at_max_f1"]
    out.append(f"At the validation-selected threshold the test split gives precision {t['precision']:.3f}, "
               f"recall {t['recall']:.3f}, F1 {t['f1']:.3f} (validation F1 was {m['val_at_max_f1']['f1']:.3f}).")
    scored = [p for p in r["per_type_recall"] if p["recall"] is not None]
    if scored:
        worst = min(scored, key=lambda p: p["recall"])
        best = max(scored, key=lambda p: p["recall"])
        out.append(f"Recall was highest for {best['anomaly_type']} ({best['recall']:.2f}, n={best['n_test']}) "
                   f"and lowest for {worst['anomaly_type']} ({worst['recall']:.2f}, n={worst['n_test']}); "
                   "per-type counts are small, so treat these as indicative.")
    fp = r["false_positive_analysis"]
    if fp["n_false_positives"]:
        top = max(fp["top_driver_counts"].items(), key=lambda kv: kv[1])
        out.append(f"There were {fp['n_false_positives']} false positives "
                   f"(FPR {fp['fp_rate']:.4f}); {fp['share_with_dq_issue'] * 100:.0f}% of them were rows that "
                   f"also carried an injected data-quality issue, and the most common top-driver feature was "
                   f"{top[0]} ({top[1]} rows).")
    else:
        out.append("There were no false positives on the test split at the selected threshold.")
    return out


def render_report(r: Dict[str, Any]) -> str:
    d, v = r["dataset"], r["validation"]
    L = ["# AutoDataGuard: Example Report", "",
         "> Generated by `python -m autodataguard run`. All numbers are computed from a **synthetic** dataset "
         f"(seed {r['config']['seed']}) and do not represent any real company.", "",
         "## 1. Dataset", "",
         f"- Raw rows: {d['n_rows_raw']} (including {d['n_duplicates_removed']} exact duplicate rows removed before modelling)",
         f"- Modelling rows: {d['n_rows_modeling']}; injected anomalies: {d['n_anomalies']} "
         f"({d['anomaly_rate_modeling'] * 100:.2f}%)",
         "", md_table(pd.DataFrame(d["splits"])), "",
         "## 2. Data quality validation", "",
         f"Overall score (mean of four dimensions): **{v['overall_score']:.4f}**", "",
         md_table(pd.DataFrame([{"dimension": k, "score": s} for k, s in v["dimension_scores"].items()]), "{:.4f}"),
         "", "Violations by rule:", "", md_table(pd.DataFrame(v["counts_by_rule"])), "",
         "Rule engine versus injected ground truth (row level):", "",
         md_table(pd.DataFrame(v["rule_engine_eval"]["per_type"])), "",
         "![dimensions](../visualizations/dq_dimension_scores.png)",
         "![violations](../visualizations/dq_violations_by_rule.png)", "",
         "## 3. Anomaly detection", "",
         f"Detector selection criterion: {r['selection_criterion']}. Selected: **{r['selected_model']}**.", ""]
    rows = []
    for name, m in r["models"].items():
        rows.append({"model": name, "val PR-AUC": m["val"]["pr_auc"], "test PR-AUC": m["test"]["pr_auc"],
                     "test ROC-AUC": m["test"]["roc_auc"], "precision": m["test"]["at_max_f1"]["precision"],
                     "recall": m["test"]["at_max_f1"]["recall"], "F1": m["test"]["at_max_f1"]["f1"]})
    L += ["Test-split results (threshold = max F1 on validation):", "", md_table(pd.DataFrame(rows)), ""]
    rows = []
    for name, m in r["models"].items():
        b = m["test"]["at_fpr_budget"]
        rows.append({"model": name, "threshold": b["threshold"], "precision": b["precision"],
                     "recall": b["recall"], "FPR": b["fpr"], "false positives": b["fp"]})
    L += [f"Test-split results (threshold = lowest with validation FPR <= {r['config']['threshold']['max_fpr']}):", "",
          md_table(pd.DataFrame(rows), "{:.4f}"), "",
          "![pr](../visualizations/pr_curves.png)", "![scores](../visualizations/score_distribution.png)", "",
          "### Recall by anomaly type", "", md_table(pd.DataFrame(r["per_type_recall"])), "",
          "![type](../visualizations/recall_by_type.png)", "", "### False-positive analysis", ""]
    fp = r["false_positive_analysis"]
    L.append(f"{fp['n_false_positives']} of {fp['n_negatives']} normal test rows were flagged "
             f"(FPR {fp['fp_rate']:.4f}).")
    if fp["examples"]:
        L += ["", "Highest-scoring false positives:", "", md_table(pd.DataFrame(fp["examples"]))]
    L += ["", "## 4. Evidence-based insights", ""] + [f"- {s}" for s in build_insights(r)]
    L += ["", "## 5. Caveats", "",
          "- Data and anomalies are synthetic and injected by simple rules; real-world performance will differ.",
          "- The rule engine is evaluated against faults injected by rules of the same kind, so its perfect "
          "recall is expected and shows correct implementation, not real-world coverage.",
          "- Anomaly types were designed by the author, so recall by type reflects that design.",
          "- Test splits contain few anomalies; metrics carry sampling uncertainty (no confidence intervals computed).",
          "- Labels were used for splitting, threshold selection and evaluation only, never as model inputs.", ""]
    return "\n".join(L)
